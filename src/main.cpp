void runCommands(Bot bot)
{
	BaseCommand& command = bot.commands[bot.index];
	switch(command.commandType)
	{
		case AttachMotorRec:
		{
			MoveAttachMotorData data;
			
			memcpy(&data, &command, sizeof(MoveAttachMotorData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();


		}
		break;

		case MoveByDegreesRec:
		{
			RobotDrivetrainData data;

			memcpy(&data, &command, sizeof(RobotDrivetrainData));

			configure(&data);



			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();




		}

		break;

		case AttachMotor:
		{
			MoveAttachMotorData data;

			memcpy(&data, &command, sizeof(MoveAttachMotorData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();


		}
		break;

		case MoveByDegrees:
		{

			bool isLeftStalled = initiateStall((MotorData&)bot.left);
			bool isRightStalled = initiateStall((MotorData&)bot.right);
			bool isCenterStalled = initiateStall((MotorData&)bot.center);

			if(isLeftStalled ||
			   isRightStalled ||
			   isCenterStalled)
			{
				bot.isRecovery = true;
			}

			RobotDrivetrainData data;

			memcpy(&data, &command, sizeof(RobotDrivetrainData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}
		break;

		case TurnByGyro:
		{

			bool isLeftStalled = initiateStall((MotorData&)bot.left);
			bool isRightStalled = initiateStall((MotorData&)bot.right);
			bool isCenterStalled = initiateStall((MotorData&)bot.center);

			if(isLeftStalled ||
			   isRightStalled ||
			   isCenterStalled)
			{
				bot.isRecovery = true;
			}

			TurnByGyroData data;

			memcpy(&data, &command, sizeof(TurnByGyroData));

			configure(&data);

			if(!hasRan(&data)) return;

			cleanup(&data);

			finalize();
		}
		break;

		case StopRecovery:
		{
			bot.isRecovery = false;
		}
		break;

		case Stop:
		{
			bot.left.motorPort.stop();
			bot.right.motorPort.stop();
			bot.center.motorPort.stop();
			printf("STOP COMMAND REACHED\n");
		}
		break;
	}

}
void RecoveryChecker(bool& isCheckForRecovery, int startindex, int endindex)
{
	if(bot.index >= startindex && bot.index <= endindex)
	{
		isCheckForRecovery = true;
	}
	else
	{
		isCheckForRecovery = false;
	}
}


